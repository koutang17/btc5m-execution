#Requires -Version 5.1
<#
.SYNOPSIS
    One-shot setup for the BTC 5m execution system.
.DESCRIPTION
    - checks the runtime prerequisites (Python, Node)
    - creates config.json from config.example.json on first run
    - generates .env with random dashboard passwords
    - creates the state / logs / data directories
    - optionally installs the Python dependencies needed by the backtester
    Nothing here starts the bot or touches an exchange account.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\install.ps1
    powershell -ExecutionPolicy Bypass -File .\install.ps1 -SkipDeps -RunDoctor
#>
[CmdletBinding()]
param(
    [switch]$SkipDeps,
    [switch]$RunDoctor
)

$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $Root

function Write-Step($msg) { Write-Host ""; Write-Host "== $msg" -ForegroundColor Cyan }
function Write-Ok($msg)   { Write-Host "   [ok]   $msg" -ForegroundColor Green }
function Write-Warn2($msg){ Write-Host "   [warn] $msg" -ForegroundColor Yellow }
function Write-Err2($msg) { Write-Host "   [fail] $msg" -ForegroundColor Red }

function New-Secret {
    param([int]$Length = 24)
    $bytes = New-Object 'byte[]' $Length
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    return [Convert]::ToBase64String($bytes).TrimEnd('=').Replace('+','-').Replace('/','_')
}

Write-Host "BTC 5m execution system - setup" -ForegroundColor White
Write-Host "root: $Root"

Write-Step "Python"
$Py = Get-Command python -ErrorAction SilentlyContinue
if (-not $Py) {
    Write-Err2 "python not found on PATH. Install Python 3.10+ and re-run."
    exit 1
}
$PyVersion = & python -c "import sys;print('%d.%d.%d'%sys.version_info[:3])"
Write-Ok "python $PyVersion ($($Py.Source))"
if ([version]($PyVersion -replace '-.*$','') -lt [version]'3.10') {
    Write-Err2 "Python 3.10 or newer is required."
    exit 1
}

Write-Step "Node.js"
$Node = Get-Command node -ErrorAction SilentlyContinue
if (-not $Node) {
    Write-Warn2 "node not found on PATH. The wallet CLI needs Node.js; install it before trading."
} else {
    Write-Ok ("node " + (& node --version))
}

Write-Step "config.json"
if (Test-Path .\config.json) {
    Write-Ok "config.json already exists - left untouched"
} else {
    Copy-Item .\config.example.json .\config.json
    Write-Ok "config.json created from config.example.json"
}

Write-Step ".env"
if (Test-Path .\.env) {
    Write-Ok ".env already exists - left untouched"
} else {
    $pass     = New-Secret 24
    $viewpass = New-Secret 18
    $lines = @(
        "# Generated by install.ps1. Never commit this file.",
        "DASH_USER=admin",
        "DASH_PASS=$pass",
        "DASH_VIEW_PASS=$viewpass",
        "NOTIFY_WEBHOOK=",
        "NOTIFY_TOKEN="
    )
    $lines | Set-Content -Path .\.env -Encoding UTF8
    Write-Ok ".env created with random dashboard passwords"
    Write-Warn2 "dashboard password: $pass   (store it now; it is not shown again)"
}

Write-Step "directories"
foreach ($d in @('state','logs','data')) {
    if (-not (Test-Path $d)) { New-Item -ItemType Directory -Path $d | Out-Null; Write-Ok "$d/ created" }
    else { Write-Ok "$d/ exists" }
}

if (-not $SkipDeps) {
    Write-Step "Python dependencies (backtest only)"
    try {
        & python -m pip install --quiet --disable-pip-version-check -r requirements.txt
        Write-Ok "requirements.txt installed"
    } catch {
        Write-Warn2 "pip install failed: $_"
        Write-Warn2 "the live bot only needs the standard library; the backtester needs pandas/numpy"
    }
}

Write-Step "Next steps"
Write-Host "   1. Edit config.json:" -ForegroundColor Gray
Write-Host "        runtime.baw_js             -> ...\@binance\agentic-wallet\dist\index.js" -ForegroundColor Gray
Write-Host "        accounts[].wallet_profile  -> where the wallet CLI keeps its session" -ForegroundColor Gray
Write-Host "        accounts[].name            -> your label" -ForegroundColor Gray
Write-Host "   2. Open the wallet CLI once and log in (QR code) for each account." -ForegroundColor Gray
Write-Host "   3. Run the self-check:   python scripts\doctor.py" -ForegroundColor Gray
Write-Host "   4. Keep risk.dry_run = true and run one full 5-minute round." -ForegroundColor Gray
Write-Host "   5. Only then set risk.dry_run = false - and start with 1u stakes." -ForegroundColor Gray

if ($RunDoctor) {
    Write-Step "doctor"
    & python .\scripts\doctor.py
}
